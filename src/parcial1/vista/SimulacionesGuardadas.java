    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
        int filaSeleccionada = tblReportes1.getSelectedRow();

        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione una simulación para exportar.",
                    "Sin selección",
                    JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        JFileChooser selectorArchivo = new JFileChooser();
        selectorArchivo.setDialogTitle("Guardar reporte CSV");
        selectorArchivo.setSelectedFile(
                new File("reporte_simulacion.csv")
        );

        int opcion = selectorArchivo.showSaveDialog(this);

        if (opcion != JFileChooser.APPROVE_OPTION) {
            return;
        }

        File archivo = selectorArchivo.getSelectedFile();

        if (!archivo.getName().toLowerCase().endsWith(".csv")) {
            archivo = new File(
                    archivo.getAbsolutePath() + ".csv"
            );
        }

        try (BufferedWriter escritor = new BufferedWriter(
        new OutputStreamWriter(
                new FileOutputStream(archivo),
                StandardCharsets.UTF_8
        )
)) {
            // Permite que Excel reconozca correctamente UTF-8
            escritor.write('\uFEFF');

            escritor.write(
             "ID;Nombre;Fecha;Resultado;Turnos;Plantas;Conejos;Lobos\n"
            );

            for (int columna = 0; columna < tblReportes1.getColumnCount(); columna++) {

                Object valor = tblReportes1.getValueAt(
                        filaSeleccionada,
                        columna
                );

                String texto = valor == null
                        ? ""
                        : valor.toString();

                texto = texto.replace("\"", "\"\"");

                escritor.write("\"" + texto + "\"");

                if (columna < tblReportes1.getColumnCount() - 1) {
                    escritor.write(";");
                }
            }

            escritor.write("\n");

            JOptionPane.showMessageDialog(
                    this,
                    "Reporte exportado correctamente en:\n"
                            + archivo.getAbsolutePath(),
                    "Exportación completada",
                    JOptionPane.INFORMATION_MESSAGE
            );

        } catch (IOException e) {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo exportar el reporte.\n"
                            + e.getMessage(),
                    "Error de exportación",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnExportarActionPerformed

