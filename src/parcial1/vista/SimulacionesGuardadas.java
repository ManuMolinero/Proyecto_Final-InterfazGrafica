    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int filaSeleccionada = tblReportes1.getSelectedRow();

    if (filaSeleccionada == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Seleccione un reporte para eliminar.",
                "Sin selección",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    int confirmacion = JOptionPane.showConfirmDialog(
            this,
            "¿Está seguro de que desea eliminar el reporte seleccionado?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION
    );

    if (confirmacion == JOptionPane.YES_OPTION) {

        int id = Integer.parseInt(
                tblReportes1.getValueAt(filaSeleccionada, 0).toString()
        );

        reporteDAO.eliminar(id);

        cargarReportes();

        JOptionPane.showMessageDialog(
                this,
                "Reporte eliminado correctamente."
        );
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

