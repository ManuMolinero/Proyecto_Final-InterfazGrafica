private void cargarReportes() {

    DefaultTableModel modeloTabla =
            (DefaultTableModel) tblReportes1.getModel();

    modeloTabla.setRowCount(0);

    List<ReporteSimulacion> reportes = reporteDAO.listar();

    for (ReporteSimulacion reporte : reportes) {

        modeloTabla.addRow(new Object[]{
            reporte.getId(),
            reporte.getNombre(),
            reporte.getFecha(),
            reporte.getResultado(),
            reporte.getTurnos(),
            reporte.getPlantas(),
            reporte.getConejos(),
            reporte.getLobos()
        });
    }

    lblCantidad.setText(
            reportes.size() + " simulaciones encontradas"
    );
}

private void filtrar() {

    String textoBuscar = txtBuscar.getText().trim();
    String resultadoSeleccionado =
            cmbResultado.getSelectedItem().toString();

    java.util.List<RowFilter<Object, Object>> filtros =
            new java.util.ArrayList<>();

    if (!textoBuscar.isEmpty()) {

        filtros.add(
                RowFilter.regexFilter(
                        "(?i)" + java.util.regex.Pattern.quote(textoBuscar)
                )
        );
    }

    if (!resultadoSeleccionado.equals("Todos")) {

        filtros.add(
                RowFilter.regexFilter(
                        "^" + java.util.regex.Pattern.quote(resultadoSeleccionado) + "$",
                        3
                )
        );
    }

    if (filtros.isEmpty()) {

        sorter.setRowFilter(null);

    } else {

        sorter.setRowFilter(
                RowFilter.andFilter(filtros)
        );
    }

    lblCantidad.setText(
            tblReportes1.getRowCount()
                    + " simulaciones encontradas"
    );
}

